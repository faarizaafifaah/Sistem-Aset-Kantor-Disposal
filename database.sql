-- Hak akses skema, tabel, dan sequence untuk frontend (role anon & authenticated)
GRANT USAGE ON SCHEMA public TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO anon, authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated;

ALTER DEFAULT PRIVILEGES IN SCHEMA public
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO anon, authenticated;

ALTER DEFAULT PRIVILEGES IN SCHEMA public
GRANT USAGE, SELECT ON SEQUENCES TO anon, authenticated;

-- Kebijakan Row Level Security (RLS) prototipe
ALTER TABLE kategori ENABLE ROW LEVEL SECURITY;
ALTER TABLE aset ENABLE ROW LEVEL SECURITY;
ALTER TABLE disposal ENABLE ROW LEVEL SECURITY;
ALTER TABLE riwayat_kondisi ENABLE ROW LEVEL SECURITY;
ALTER TABLE log_pengunjung ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "kategori_akses_prototipe" ON kategori;

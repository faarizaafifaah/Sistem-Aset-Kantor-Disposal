CREATE TABLE IF NOT EXISTS kategori (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_kategori VARCHAR(100) NOT NULL UNIQUE,
    deskripsi TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS aset (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode_aset VARCHAR(50) NOT NULL UNIQUE,
    nama_aset VARCHAR(150) NOT NULL,
    kategori_id BIGINT REFERENCES kategori(id),
    lokasi VARCHAR(150),
    tanggal_perolehan DATE NOT NULL,
    harga_perolehan NUMERIC(15,2) DEFAULT 0,
    masa_manfaat_tahun INTEGER NOT NULL DEFAULT 5,
    kondisi VARCHAR(20) NOT NULL DEFAULT 'Baik'
        CHECK (kondisi IN ('Baik', 'Rusak', 'Disposal')),
    keterangan TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS disposal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aset_id BIGINT NOT NULL REFERENCES aset(id) ON DELETE CASCADE,
    tanggal_disposal DATE NOT NULL DEFAULT CURRENT_DATE,
    alasan TEXT NOT NULL,
    nilai_disposal NUMERIC(15,2) DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS riwayat_kondisi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aset_id BIGINT NOT NULL REFERENCES aset(id) ON DELETE CASCADE,
    kondisi_baru VARCHAR(20) NOT NULL
        CHECK (kondisi_baru IN ('Baik', 'Rusak', 'Disposal')),
    tanggal_laporan DATE NOT NULL DEFAULT CURRENT_DATE,
    keterangan TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS log_pengunjung (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visitor_code VARCHAR(30) NOT NULL,
    nama_pengunjung VARCHAR(100) DEFAULT 'Tamu / Pengunjung',
    perangkat VARCHAR(50),
    browser VARCHAR(50),
    sistem_operasi VARCHAR(50),
    resolusi_layar VARCHAR(30),
    waktu_akses TIMESTAMPTZ DEFAULT NOW()
);

-- Pastikan relasi mendukung ON DELETE CASCADE jika tabel sudah dibuat sebelumnya
ALTER TABLE disposal
DROP CONSTRAINT IF EXISTS disposal_aset_id_fkey,
ADD CONSTRAINT disposal_aset_id_fkey
    FOREIGN KEY (aset_id) REFERENCES aset(id) ON DELETE CASCADE;

ALTER TABLE riwayat_kondisi
DROP CONSTRAINT IF EXISTS riwayat_kondisi_aset_id_fkey,
ADD CONSTRAINT riwayat_kondisi_aset_id_fkey
    FOREIGN KEY (aset_id) REFERENCES aset(id) ON DELETE CASCADE;

CREATE INDEX IF NOT EXISTS idx_aset_kategori
    ON aset(kategori_id);

CREATE INDEX IF NOT EXISTS idx_disposal_aset
    ON disposal(aset_id);

CREATE INDEX IF NOT EXISTS idx_riwayat_aset
    ON riwayat_kondisi(aset_id);

CREATE INDEX IF NOT EXISTS idx_log_pengunjung_waktu
    ON log_pengunjung(waktu_akses DESC);

